import { expect } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";
import type { Building, RouteResponse } from "../../src/api/types.ts";
import { test } from "./isolated-campus.ts";

test("versioned API: stable waypoint IDs guide a real C2 walk", async ({ page, request }) => {
  const evidence = process.env.UNINAV_EVIDENCE_DIR ?? "docs/verification/h1-routing";
  await mkdir(evidence, { recursive: true });
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const places = await (await request.get("/buildings")).json() as Building[];
  const target = places.find((place) => place.name === "ICETEX")!;
  expect(target.code).toBe("ucc:floor1:p06");
  expect(target.elevation_m).toBe(3.5);
  await page.goto("/app/");
  await expect(page.locator("#model-status")).toContainText("3 references aligned");
  await page.locator("#open-login").click();
  await page.getByLabel("Username", { exact: true }).fill("student");
  await page.getByLabel("Password", { exact: true }).fill("demo1234");
  await page.locator("#login-submit").click();
  await expect(page.locator("#session-user")).toHaveText("student");
  await page.locator("#search").fill("ICETEX");
  await page.locator("#place-list button").first().click();
  const response = page.waitForResponse((r) => r.url().endsWith("/routes/calculate"));
  await page.locator("#calculate").click();
  const route = await (await response).json() as RouteResponse;
  expect(route.waypoints?.at(-1)?.id).toBe(target.id);
  expect(route.waypoints?.every((p) => p.code.startsWith("ucc:floor1:") && p.elevation_m === 3.5)).toBe(true);
  expect(route.steps.every((step) => step.path_id && step.connection_code)).toBe(true);
  await expect(page.locator("#travel-status")).toHaveAttribute("data-state", "ready");
  await page.locator("#follow").click();
  await expect(page.locator("#travel-status")).toHaveAttribute("data-state", "arrived", { timeout: 60000 });
  const finalPosition = (await page.locator("#travel-status").getAttribute("data-position"))!.split(",").map(Number);
  const finalError = Math.hypot(finalPosition[0] - target.x, finalPosition[1] - target.elevation_m!, finalPosition[2] + target.y);
  expect(finalError).toBeLessThan(0.02);
  expect(errors).toEqual([]);
  await writeFile(`${evidence}/structured-route.json`, JSON.stringify({ route, finalPosition, finalError, pageErrors: errors }, null, 2));
  await page.screenshot({ path: `${evidence}/structured-arrival.png`, fullPage: true });
});
